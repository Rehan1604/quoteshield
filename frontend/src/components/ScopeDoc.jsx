import { useState } from 'react'
import styles from './ScopeDoc.module.css'

function healthScore(data) {
  let score = 0
  if (data.deliverables?.length >= 3)    score += 25
  if (data.milestones?.length >= 2)      score += 20
  if (data.not_included?.length >= 2)    score += 20
  if (data.assumptions?.length >= 2)     score += 15
  if (data.estimated_hours > 0)          score += 10
  if (data.revision_policy?.length > 20) score += 10
  return Math.min(score, 100)
}

function healthLabel(score) {
  if (score >= 85) return { label: 'Solid',  color: 'var(--success)' }
  if (score >= 60) return { label: 'Good',   color: 'var(--warn)' }
  return                  { label: 'Thin',   color: 'var(--danger)' }
}

export default function ScopeDoc({ data, onReset }) {
  const [copied, setCopied] = useState(null)

  const score  = healthScore(data)
  const health = healthLabel(score)

  function copyText() {
    const lines = [
      `PROJECT: ${data.project_title}`, '',
      'SUMMARY', data.summary, '',
      'DELIVERABLES', ...data.deliverables.map(d => `• ${d}`), '',
      'MILESTONES', ...data.milestones.map(m => `• ${m.name} (${m.duration}): ${m.description}`), '',
      'NOT INCLUDED', ...data.not_included.map(n => `• ${n}`), '',
      'ASSUMPTIONS', ...data.assumptions.map(a => `• ${a}`), '',
      `ESTIMATED HOURS: ${data.estimated_hours}h`, '',
      'REVISION POLICY', data.revision_policy, '',
      '— Generated by QuoteShield (local AI, your data never left your machine)',
    ]
    navigator.clipboard.writeText(lines.join('\n'))
    setCopied('text')
    setTimeout(() => setCopied(null), 2000)
  }

  function copyMarkdown() {
    const md = [
      `# ${data.project_title}`, '',
      '## Summary', data.summary, '',
      '## Deliverables', ...data.deliverables.map(d => `- ${d}`), '',
      '## Milestones', ...data.milestones.map(m => `- **${m.name}** *(${m.duration})*: ${m.description}`), '',
      '## Not Included', ...data.not_included.map(n => `- ${n}`), '',
      '## Assumptions', ...data.assumptions.map(a => `- ${a}`), '',
      '## Estimate', `**${data.estimated_hours} hours**`, '',
      '## Revision Policy', data.revision_policy, '',
      '---',
      '*Generated by QuoteShield — local AI, your data never left your machine*',
    ]
    navigator.clipboard.writeText(md.join('\n'))
    setCopied('md')
    setTimeout(() => setCopied(null), 2000)
  }

  return (
    <div className={styles.wrapper}>

      <div className={styles.topBar}>
        <div className={styles.titleBlock}>
          <span className={styles.badge}>Scope doc ready</span>
          <h1 className={styles.projectTitle}>{data.project_title}</h1>
        </div>
        <div className={styles.actions}>
          <button className={styles.actionBtn} onClick={copyText}>
            {copied === 'text' ? '✓ Copied' : 'Copy text'}
          </button>
          <button className={styles.actionBtn} onClick={copyMarkdown}>
            {copied === 'md' ? '✓ Copied' : 'Copy MD'}
          </button>
          <button className={styles.resetBtn} onClick={onReset}>← New scope</button>
        </div>
      </div>

      <div className={styles.summary}><p>{data.summary}</p></div>

      <div className={styles.statsRow}>
        <div className={styles.stat}>
          <span className={styles.statNum} style={{ color: 'var(--accent)' }}>{data.estimated_hours}h</span>
          <span className={styles.statLabel}>Estimated</span>
        </div>
        <div className={styles.stat}>
          <span className={styles.statNum} style={{ color: 'var(--accent2)' }}>{data.deliverables.length}</span>
          <span className={styles.statLabel}>Deliverables</span>
        </div>
        <div className={styles.stat}>
          <span className={styles.statNum} style={{ color: 'var(--accent3)' }}>{data.milestones.length}</span>
          <span className={styles.statLabel}>Milestones</span>
        </div>
        <div className={styles.stat}>
          <span className={styles.statNum} style={{ color: 'var(--danger)' }}>{data.not_included.length}</span>
          <span className={styles.statLabel}>Exclusions</span>
        </div>
        <div className={`${styles.stat} ${styles.statHealth}`}>
          <span className={styles.statNum} style={{ color: health.color }}>{score}</span>
          <span className={styles.statLabel}>
            Health
            <span className={styles.healthPill} style={{ color: health.color, borderColor: health.color }}>
              {health.label}
            </span>
          </span>
        </div>
      </div>

      <div className={styles.grid}>
        <div className={styles.card}>
          <h2 className={styles.cardTitle} style={{ color: 'var(--accent)' }}>Deliverables</h2>
          <ul className={styles.list}>
            {data.deliverables.map((d, i) => (
              <li key={i} className={styles.listItem}>
                <span className={styles.dot} style={{ background: 'var(--accent)' }} />{d}
              </li>
            ))}
          </ul>
        </div>
        <div className={styles.card}>
          <h2 className={styles.cardTitle} style={{ color: 'var(--danger)' }}>Not included</h2>
          <ul className={styles.list}>
            {data.not_included.map((n, i) => (
              <li key={i} className={styles.listItem}>
                <span className={styles.dot} style={{ background: 'var(--danger)' }} />{n}
              </li>
            ))}
          </ul>
        </div>
      </div>

      <div className={styles.card}>
        <h2 className={styles.cardTitle} style={{ color: 'var(--accent2)' }}>Milestones</h2>
        <div className={styles.timeline}>
          {data.milestones.map((m, i) => (
            <div key={i} className={styles.timelineItem}>
              <div className={styles.timelineLeft}>
                <div className={styles.timelineDot} />
                {i < data.milestones.length - 1 && <div className={styles.timelineLine} />}
              </div>
              <div className={styles.timelineContent}>
                <div className={styles.timelineHead}>
                  <span className={styles.milestoneName}>{m.name}</span>
                  <span className={styles.milestoneDuration}>{m.duration}</span>
                </div>
                <p className={styles.milestoneDesc}>{m.description}</p>
              </div>
            </div>
          ))}
        </div>
      </div>

      <div className={styles.grid}>
        <div className={styles.card}>
          <h2 className={styles.cardTitle} style={{ color: 'var(--success)' }}>Assumptions</h2>
          <ul className={styles.list}>
            {data.assumptions.map((a, i) => (
              <li key={i} className={styles.listItem}>
                <span className={styles.dot} style={{ background: 'var(--success)' }} />{a}
              </li>
            ))}
          </ul>
        </div>
        <div className={styles.card}>
          <h2 className={styles.cardTitle} style={{ color: 'var(--text2)' }}>Revision policy</h2>
          <p className={styles.revisionText}>{data.revision_policy}</p>
        </div>
      </div>

      <div className={styles.footer}>
        ⚔️ Generated by QuoteShield — Mistral 7B · local inference · your data never left your machine
      </div>
    </div>
  )
}
